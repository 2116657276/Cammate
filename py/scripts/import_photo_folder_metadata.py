def _ensure_import_user(
    conn: Any,
    email_prefix: str,
    ordinal: int,
    nickname: str,
    created_at: int,
    used_nicknames: set[str],
) -> dict[str, Any]:
    final_nickname = _choose_unique_nickname(nickname, ordinal=ordinal, used_nicknames=used_nicknames)
    email = f"{email_prefix}_{ordinal:03d}@cammate.local"
    cur = conn.execute(
        """
        INSERT INTO users(email, password_hash, password_salt, nickname, created_at)
        VALUES (?, ?, ?, ?, ?)
        """,
        (email, "import_password_hash", "import_password_salt", final_nickname, created_at),
    )
    return {"id": int(cur.lastrowid), "nickname": final_nickname, "email": email}


def _insert_feedback(
    conn: Any,
    user_id: int,
    photo_path: Path,
    metadata: ParsedMetadata,
    created_at: int,
    batch_label: str,
) -> int:
    session_meta = json.dumps(
        {
            "import_batch": batch_label,
            "source_filename": photo_path.name,
            "tags": metadata.tags,
            "primary_category": metadata.primary_category,
        },
        ensure_ascii=False,
    )
    cur = conn.execute(
        """
        INSERT INTO feedback(
            user_id, rating, scene, tip_text, photo_uri,
            is_retouch, review_text, session_meta, created_at
        ) VALUES (?, ?, ?, ?, ?, 0, ?, ?, ?)
        """,
        (
            user_id,
            metadata.rating,
            metadata.scene_type,
            _tip_text_for_category(metadata.primary_category),
            str(photo_path),
            metadata.review_text,
            session_meta,
            created_at,
        ),
    )
    return int(cur.lastrowid)


