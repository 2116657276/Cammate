def _populate_engagement(conn: Any, imported_posts: list[ImportedPost], rng: random.Random) -> None:
    if not imported_posts:
        return

    user_rows = conn.execute("SELECT id, nickname FROM users ORDER BY id").fetchall()
    all_users = [{"id": int(row["id"]), "nickname": str(row["nickname"] or "")} for row in user_rows]
    imported_by_id = {item.user_id: item for item in imported_posts}

    for post in imported_posts:
        like_candidates = [user for user in all_users if user["id"] != post.user_id]
        rng.shuffle(like_candidates)
        # Avoid saturating every imported post at the same ceiling when the
        # target likes exceed the current community size.
        like_ceiling = max(8, len(like_candidates) - rng.randint(2, max(6, len(like_candidates) // 2)))
        target_like_count = min(post.like_count, len(like_candidates), like_ceiling)
        like_time = post.created_at + rng.randint(600, 1800)
        for liker in like_candidates[:target_like_count]:
            conn.execute(
                """
                INSERT OR IGNORE INTO community_post_likes(post_id, user_id, created_at)
                VALUES (?, ?, ?)
                """,
                (post.post_id, liker["id"], like_time),
            )
            like_time += rng.randint(240, 900)

        comment_candidates = [user for user in all_users if user["id"] != post.user_id]
        rng.shuffle(comment_candidates)
        comments = _build_comment_list(post=post, desired_count=post.comment_count)
        for index, text in enumerate(comments):
            commenter = comment_candidates[index % len(comment_candidates)] if comment_candidates else {"id": post.user_id}
            conn.execute(
                """
                INSERT INTO community_post_comments(post_id, user_id, text, created_at)
                VALUES (?, ?, ?, ?)
                """,
                (
                    post.post_id,
                    commenter["id"],
                    text,
                    post.created_at + rng.randint(1800, 3600) + index * rng.randint(300, 900),
                ),
            )


def _build_comment_list(post: ImportedPost, desired_count: int) -> list[str]:
    desired = max(0, desired_count)
    comments = [text for text in post.comments if text.strip()]
    templates = _comment_templates_for_category(post.primary_category)

    index = 0
    while len(comments) < desired and templates:
        template = templates[index % len(templates)]
        comments.append(template.format(place=post.place_tag, nickname=post.nickname))
        index += 1
    return comments[:desired]


def _normalize_primary_category(value: str) -> str:
    raw = value.strip().lower()
    mapping = {
        "portrait": "portrait",
        "people": "portrait",
        "person": "portrait",
        "group": "portrait",
        "landscape": "landscape",
        "travel": "travel",
        "night": "night",
        "food": "food",
        "pet": "pet",
        "flower": "flower",
        "indoor": "indoor",
        "general": "general",
    }
    return mapping.get(raw, "general")


def _map_scene_type(value: str) -> str:
    raw = value.strip().lower()
    if raw in {"portrait", "food", "night", "landscape", "general", "pet", "flower"}:
        return raw
    category = _normalize_primary_category(raw)
    if category in {"portrait", "food", "night", "pet", "flower"}:
        return category
    if category in {"landscape", "travel"}:
        return "landscape"
    return "general"


