def _normalize_nickname(value: str) -> str:
    compact = " ".join(value.strip().split())
    return compact[:20]


def _choose_unique_nickname(nickname: str, ordinal: int, used_nicknames: set[str]) -> str:
    candidates = [nickname] if nickname else []
    if ordinal - 1 < len(_NICKNAME_POOL):
        candidates.append(_NICKNAME_POOL[ordinal - 1])
    candidates.extend(_NICKNAME_POOL)
    candidates.append(f"拍友{ordinal:02d}")

    for candidate in candidates:
        base = _normalize_nickname(candidate)
        if not base:
            continue
        if base not in used_nicknames:
            used_nicknames.add(base)
            return base

    final_name = f"拍友{ordinal:02d}"
    used_nicknames.add(final_name)
    return final_name


def _pick_created_at(captured_at: str, photo_path: Path, index: int) -> int:
    text = captured_at.strip()
    if text:
        try:
            if text.endswith("Z"):
                text = text[:-1] + "+00:00"
            return int(datetime.fromisoformat(text).timestamp())
        except Exception:
            pass
    return int(photo_path.stat().st_mtime) + index * 173


def _normalize_image_bytes(photo_path: Path) -> bytes:
    with Image.open(photo_path) as raw:
        image = ImageOps.exif_transpose(raw).convert("RGB")
        max_side = 1920
        if max(image.size) > max_side:
            image.thumbnail((max_side, max_side), Image.Resampling.LANCZOS)
        output = Path(photo_path.name).suffix.lower()
        mime = "JPEG"
        from io import BytesIO

        buf = BytesIO()
        image.save(buf, format=mime, quality=90, optimize=True)
        data = buf.getvalue()
        if not data:
            raise RuntimeError(f"failed to normalize image: {photo_path}")
        return data


def _save_import_image_bytes(photo_dir: Path, image_name: str, image_bytes: bytes) -> Path:
    upload_dir = PY_ROOT / "uploads" / "community"
    upload_dir.mkdir(parents=True, exist_ok=True)
    sanitized = re.sub(r"[^0-9A-Za-z_\-.一-龥]+", "_", Path(image_name).stem)[:60].strip("_") or "photo"
    target = upload_dir / f"import_{sanitized}.jpg"
    suffix = 1
    while target.exists():
        target = upload_dir / f"import_{sanitized}_{suffix}.jpg"
        suffix += 1
    target.write_bytes(image_bytes)
    return target.resolve()


def _delete_local_file(raw_path: str) -> None:
    path = Path(str(raw_path or "").strip())
    if not str(path):
        return
    try:
        resolved = path.resolve() if path.is_absolute() else (PY_ROOT / path).resolve()
        if resolved.exists():
            resolved.unlink()
    except Exception:
        return


def _clamp_int(value: Any, default: int, min_value: int, max_value: int) -> int:
    try:
        num = int(str(value).strip())
    except Exception:
        num = default
    return max(min_value, min(max_value, num))


